# -*- coding: utf-8 -*-
"""
Bundles the ES modules in js/ into one classic script, js/bundle.js.

The modules stay the source of truth. This exists because a page opened straight
from disk (file://) has a null origin, so Chrome blocks `<script type="module">`
outright and NOTHING boots — filters, counters, mobile nav, the lot. A classic
script has no such restriction, so the built site behaves the same whether it is
served over HTTP or double-clicked.

Each module keeps its own scope (no top-level name collisions between files) and
passes its exports through a shared registry, so `import` order still matters:
ORDER below is dependency order.
"""
import io
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JS = os.path.join(ROOT, "js")

ORDER = ["navigation.js", "animations.js", "gallery.js", "media.js", "contact.js", "main.js"]

IMPORT_NAMES = re.compile(r"import\s*\{([^}]*)\}\s*from\s*'[^']+'\s*;?", re.S)
EXPORT_DECL = re.compile(r"^export\s+(?:function|const|let|var|class)\s+([A-Za-z_$][\w$]*)", re.M)


def strip_module(src):
    """Returns (body, imported_names, exported_names) with the ESM syntax removed."""
    imported = []
    for match in IMPORT_NAMES.finditer(src):
        imported += [n.strip() for n in match.group(1).split(",") if n.strip()]
    body = IMPORT_NAMES.sub("", src)
    exported = EXPORT_DECL.findall(body)
    body = re.sub(r"^export\s+", "", body, flags=re.M)
    return body.strip(), imported, exported


def build():
    parts = [
        "/* Generated by build/bundle_js.py - do not edit. Source: js/*.js */",
        "(function () {",
        "  'use strict';",
        "  var __mod = {};",
    ]
    for name in ORDER:
        src = io.open(os.path.join(JS, name), encoding="utf-8").read()
        body, imported, exported = strip_module(src)
        parts.append(f"\n  /* ---------- {name} ---------- */")
        parts.append("  (function () {")
        for ident in imported:
            parts.append(f"    var {ident} = __mod.{ident};")
        parts.append("\n".join("    " + line if line else "" for line in body.split("\n")))
        for ident in exported:
            parts.append(f"    __mod.{ident} = {ident};")
        parts.append("  })();")
    parts.append("})();")
    out = "\n".join(parts) + "\n"
    path = os.path.join(JS, "bundle.js")
    io.open(path, "w", encoding="utf-8", newline="\n").write(out)
    return path, len(out)


if __name__ == "__main__":
    path, size = build()
    print(f"{os.path.relpath(path, ROOT):24} {size:>8,} bytes")
